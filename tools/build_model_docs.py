    def delta_cell(self, m: Model, ref: Model | None, bat: str, metric: str) -> str:
        """'+3 (6↑/3↓, n.s.)' style comparison for one metric of one battery."""
        if ref is None or bat not in m.summary or bat not in ref.summary:
            return "—"
        a, r = m.summary[bat], ref.summary[bat]
        if bat == "att10":
            col, higher_better = {"pass10": ("pass10", True), "best_sep": ("best_sep", False)}[metric]
            t = self.paired(a["perseed"], r["perseed"], col)
            diff = a[metric] - r[metric]
        elif metric == "on_time":
            t = self.paired_mean(a["perseed"], r["perseed"], "on_time")
            s = f"{t['diff']:+.3f} (SE {t['se']:.3f})".replace("-", "−", 1)
            return f"<strong>{s}</strong>" if t["sig"] else f"{s}, n.s."
        else:
            col = {"solved": "solved", "hard_solved": "hard", "separation_lost": "sep"}[metric]
            higher_better = metric != "separation_lost"
            t = self.paired(a["perseed"], r["perseed"], col)
            diff = a[metric] - r[metric]
        up, down = t["up"], t["down"]
        if metric in ("separation_lost", "best_sep"):
            detail = f"{down} fixed, {up} new"
        else:
            detail = f"{up} gained, {down} lost"
        sig = t["p"] < 0.05
        s = f"{diff:+d} ({detail}".replace("-", "−", 1)
        s += f"; z {t['z']:+.2f})".replace("-", "−") if sig else ", n.s.)"
        return f"<strong>{s}</strong>" if sig else s

