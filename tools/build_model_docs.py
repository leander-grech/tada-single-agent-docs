    # ------------------------------------------------------------------ standard render slots
    def render_slots(self, m: Model) -> list[dict]:
        """comparison seed / best solved seed / most typical failure, each filled or a placeholder."""
        slots = []
        dets = [r for r in m.renders if r["known"] and r.get("kind") == "det" and r.get("seed") is not None]
        ps = m.summary.get("f20", {}).get("perseed") if m.track == "windowed" else None
        # 1 comparison seed
        hit = next((r for r in dets if r["seed"] == self.comparison_seed), None)
        slots.append({"slot": "Comparison scenario", "render": hit, "seed": self.comparison_seed,
                      "why": "the scenario every agent is rendered on, deterministic"})
        if ps is None:
            return slots + [{"slot": "Best solved seed", "render": None, "seed": None, "why": "needs a 20-flight evaluation"},
                            {"slot": "Most typical failure", "render": None, "seed": None, "why": "needs a 20-flight evaluation"}]
        # 2 best solved: among deterministic solves, smallest worst deviation, then fewest clearances
        solved = ps[ps.solved]
        best_seed = None
        if len(solved):
            order = solved.sort_values([c for c in ["max_dev", "clearances"] if c in solved.columns])
            best_seed = int(order.index[0])
        hit = next((r for r in dets if best_seed is not None and r["seed"] == best_seed), None) or \
            next((r for r in dets if r["seed"] in set(solved.index) and r["seed"] != self.comparison_seed), None)
        slots.append({"slot": "Best solved seed", "render": hit, "seed": best_seed,
                      "why": "deterministic solve with the smallest worst-flight deviation" if best_seed else "no seed solved deterministically"})
        # 3 most typical failure: the more common failure class; the seed nearest that class's median on-time
        fail = ps[~ps.solved]
        typ_seed, cls = None, None
        if len(fail):
            n_sep, n_prec = int(fail.sep.sum()), int((~fail.sep).sum())
            cls = "loss of separation" if n_sep > n_prec else "precision (safe, not all on time)"
            pool = fail[fail.sep] if n_sep > n_prec else fail[~fail.sep]
            med = pool.on_time.median()
            typ_seed = int((pool.on_time - med).abs().sort_index().idxmin())
            same_class = set(pool.index)
            hit = next((r for r in dets if r["seed"] == typ_seed), None) or \
                next((r for r in dets if r["seed"] in same_class), None)
        else:
            hit = None
        slots.append({"slot": "Most typical failure", "render": hit, "seed": typ_seed,
                      "why": f"most common failure class: {cls}; seed nearest that class's median on-time rate" if cls else "no failures"})
        return slots

