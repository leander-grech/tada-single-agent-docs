#!/usr/bin/env python
"""Build the generated pages of the TADA docs from models.yaml and the code repo's evaluation files.

    python tools/build_model_docs.py [--code-repo PATH] [--check]

Reads (never writes) the code repo: evaluation CSVs, run_meta.json, track.csv / progress_scored.csv
and render metadata (*_solutions.json). Writes, in this repo:

    docs/models/index.md        leaderboard (windowed and 10-aircraft)
    docs/models/best.md         the current champion
    docs/models/<id>.md         one report card per model
    docs/renders.md             render gallery, every video credited
    docs/index.md               the "current best" box, between <!-- gen:best-box --> markers
    docs/**/*.md                any <!-- gen:compare ... --> / <!-- gen:render ... --> block
    mkdocs.yml                  the model-card nav, between "# BEGIN/END generated model nav"
    BACKFILL.md                 every missing evaluation and render, per model

The build refuses to run if a video under docs/assets/renders/ is not in the registry, if a
registered render lacks the metadata its caption needs, or if a hand-written page embeds a
<video> directly (pages embed renders with <!-- gen:render file=... --><!-- /gen -->).
--check builds everything in memory and fails if any output file would change.
"""
