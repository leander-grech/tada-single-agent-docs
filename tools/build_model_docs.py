    def compare_table(self, ids: list[str], bats: list[str]) -> str:
        ms = [self.models[i] for i in ids if i in self.models]
        rows = []
        def add(label, getter):
            vals = []
            for m in ms:
                try:
                    v = getter(m)
                except (KeyError, TypeError):
                    v = None
                vals.append("—" if v is None else v)
            rows.append(f"<tr><td>{label}</td>" + "".join(f"<td>{v}</td>" for v in vals) + "</tr>")
        for bat in bats:
            if bat == "att10":
                add("pass@10 (seeds)", lambda m: m.summary["att10"]["pass10"])
                add("separation lost, best of 10", lambda m: m.summary["att10"]["best_sep"])
                continue
            lab = {"f20": "20-flight", "s2x20": "stitched 2×20", "la4": "with lookahead"}[bat]
            add(f"{lab}: solved", lambda m, bat=bat: m.summary[bat]["solved"])
            add(f"{lab}: hard-solved", lambda m, bat=bat: m.summary[bat]["hard_solved"])
            add(f"{lab}: separation lost", lambda m, bat=bat: m.summary[bat]["separation_lost"])
            add(f"{lab}: flights on time", lambda m, bat=bat: f"{m.summary[bat]['on_time']:.3f}")
            if bat == "f20":
                add(f"{lab}: clearances / stream", lambda m: fmt(m.summary["f20"].get("clearances"), 1))
                add(f"{lab}: AMAN swaps / stream", lambda m: fmt(m.summary["f20"].get("swaps"), 2))
        head = "".join(f'<th><a href="{self._href(m.id)}">{m.id}</a></th>' for m in ms)
        return (f'<table class="tada-table tada-compare"><thead><tr><th>100 seeds, deterministic unless stated</th>{head}</tr></thead>'
                f"<tbody>{''.join(rows)}</tbody></table>\n\n")

